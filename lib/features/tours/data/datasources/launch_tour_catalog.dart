import '../../domain/entities/tour_package.dart';

class _StopSpec {
  const _StopSpec(this.day, this.kind, this.title, this.subtitle);
  final int day;
  final TourStopKind kind;
  final String title;
  final String subtitle;
}

TourStop _stop(String id, int day, int order, TourStopKind kind, String title, String subtitle) =>
    TourStop(
      id: id,
      dayIndex: day,
      orderIndex: order,
      kind: kind,
      title: title,
      subtitle: subtitle,
      imageUrl: '',
      imageAttribution: 'Edible · doğrulanmış uzak görsel kaynağı',
    );

TourPackage _tour({
  required String id,
  required String countryCode,
  required String countryName,
  required String cityName,
  required String title,
  required String summary,
  required List<_StopSpec> stops,
}) {
  final built = <TourStop>[];
  for (var i = 0; i < stops.length; i++) {
    final stop = stops[i];
    built.add(_stop('${id}_$i', stop.day, i, stop.kind, stop.title, stop.subtitle));
  }
  final days = built.isEmpty ? 1 : built.map((e) => e.dayIndex).reduce((a, b) => a > b ? a : b) + 1;
  return TourPackage(
    id: id,
    countryCode: countryCode,
    countryName: countryName,
    cityName: cityName,
    title: title,
    summary: summary,
    days: days,
    coverImageUrl: '',
    coverAttribution: 'Edible · doğrulanmış uzak görsel kaynağı',
    favoriteCount: 0,
    ratingAverage: 0,
    ratingCount: 0,
    stops: built,
  );
}

