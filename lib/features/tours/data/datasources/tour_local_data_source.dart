TourPackage _package(String id,String code,String country,String city,String title,String summary,
  String cover,List<TourStop> stops) {
  final days = _legacyDays[id] ?? 4;
  final remapped = <TourStop>[];
  for (var i = 0; i < stops.length; i++) {
    final stop = stops[i];
    final day = i < days ? i : i % days;
    remapped.add(TourStop(
      id: stop.id,
      dayIndex: day,
      orderIndex: i,
      kind: stop.kind,
      title: stop.title,
      subtitle: stop.subtitle,
      imageUrl: stop.imageUrl,
      imageAttribution: stop.imageAttribution,
      latitude: stop.latitude,
      longitude: stop.longitude,
    ));
  }
  return TourPackage(
    id:id,countryCode:code,countryName:country,cityName:city,title:title,summary:summary,
    days:days,coverImageUrl:cover,coverAttribution:_commons,favoriteCount:0,
    ratingAverage:0,ratingCount:0,stops:remapped);
}

