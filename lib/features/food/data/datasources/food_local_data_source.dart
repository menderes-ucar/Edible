import '../models/food_details_model.dart';
import 'global_food_intelligence_catalog.dart';

class FoodLocalDataSource {
  const FoodLocalDataSource();
  List<FoodDetailsModel> getDetails({
    required Iterable<String> contentIds,
    required String languageCode,
  }) {
    final wanted = contentIds.toSet();
    if (wanted.isEmpty) return const [];

    final byId = <String, FoodDetailsModel>{
      for (final item in getGlobalFoodIntelligenceCatalog(
        contentIds: wanted,
        languageCode: languageCode,
      ))
        item.contentId: item,
      for (final item in _seed.where((item) => wanted.contains(item.contentId)))
        item.contentId: item,
    };

    return byId.values.toList(growable: false);
  }
}

