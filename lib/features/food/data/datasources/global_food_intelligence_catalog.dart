List<FoodDetailsModel> getGlobalFoodIntelligenceCatalog({
  required Iterable<String> contentIds,
  required String languageCode,
}) {
  final wanted = contentIds.toSet();
  if (wanted.isEmpty) return const [];

  final locale = _supportedLocale(languageCode);
  return _items
      .where((item) => wanted.contains(item.contentId))
      .map((item) => item.toModel(locale))
      .toList(growable: false);
}

String _supportedLocale(String value) {
  const supported = {'en', 'tr', 'de', 'fr', 'es', 'it', 'ar', 'zh', 'ru', 'ko', 'ja', 'pt', 'nl'};
  final normalized = value.trim().toLowerCase();
  return supported.contains(normalized) ? normalized : 'en';
}

class _FoodCatalogItem {
  const _FoodCatalogItem({
    required this.contentId,
    required this.currencyCode,
    required this.kind,
  });

  final String contentId;
  final String currencyCode;
  final String kind;

  FoodDetailsModel toModel(String locale) {
    final copy = _copy[locale] ?? _copy['en']!;
    return FoodDetailsModel(
      contentId: contentId,
      currencyCode: currencyCode,
      // Deliberately null until editorial verification. We do not guess
      // dietary/allergen/price claims in a travel product.
      typicalPriceMin: null,
      typicalPriceMax: null,
      spicyLevel: null,
      vegetarian: null,
      vegan: null,
      halal: null,
      containsPork: null,
      containsAlcohol: null,
      glutenFree: null,
      ingredients: const [],
      allergens: const [],
      portionInfo: copy.portion(kind),
      howLocalsEat: copy.how(kind),
      whenLocalsEat: copy.when(kind),
      beforeYouOrder: copy.beforeYouOrder,
    );
  }
}

